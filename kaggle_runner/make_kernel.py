"""Build a Kaggle kernel folder that runs one experiment at a pinned commit.

Usage (from the GitHub workflow):
    python kaggle_runner/make_kernel.py CONFIG --username U --sha SHA --run-id ID --out DIR
    kaggle kernels push -p DIR

The generated ``run.py`` installs batteryct from GitHub at exactly ``SHA``, finds the
attached private dataset under /kaggle/input, runs ``batteryct experiment`` and
writes everything to /kaggle/working/<run_id>/ (collected later by collect.py).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

REPO = "https://github.com/data2dev/batteryct_inspector.git"

RUN_PY = '''"""Auto-generated by kaggle_runner/make_kernel.py. Do not edit on Kaggle."""
import json, os, platform, subprocess, sys, time

RUN_ID = {run_id!r}
SHA = {sha!r}
CONFIG_NAME = {config_name!r}
CONFIG_YAML = {config_yaml!r}
REPO = {repo!r}

out = os.path.join("/kaggle/working", RUN_ID)
os.makedirs(out, exist_ok=True)
t0 = time.time()
meta = {{"run_id": RUN_ID, "git_sha": SHA, "config_name": CONFIG_NAME, "status": "started"}}


def save_meta():
    with open(os.path.join(out, "run_meta.json"), "w") as f:
        json.dump(meta, f, indent=2)


save_meta()
try:
    subprocess.check_call(
        [sys.executable, "-m", "pip", "install", "-q", f"git+{{REPO}}@{{SHA}}"]
    )
    cfg_path = os.path.join(out, "config.yaml")
    with open(cfg_path, "w") as f:
        f.write(CONFIG_YAML)
    subprocess.check_call(
        ["batteryct", "experiment", cfg_path, "--data", "/kaggle/input", "--out", out]
    )
    meta["status"] = "complete"
except Exception as e:  # record the failure in the collected output, then fail the kernel
    meta["status"] = "error"
    meta["error"] = repr(e)
    raise
finally:
    meta["runtime_s"] = round(time.time() - t0, 1)
    meta["python"] = platform.python_version()
    try:
        import torch  # noqa: F401
        meta["gpu"] = torch.cuda.get_device_name(0) if torch.cuda.is_available() else None
    except Exception:
        meta["gpu"] = None
    save_meta()
'''


def kernel_slug(config_name: str) -> str:
    slug = "batteryct-" + "".join(c if c.isalnum() else "-" for c in config_name.lower())
    return "-".join(p for p in slug.split("-") if p)[:50]


def build(config: Path, username: str, sha: str, run_id: str, out: Path) -> Path:
    raw_text = config.read_text()
    cfg = yaml.safe_load(raw_text) or {}
    for key in ("name", "dataset"):
        if not cfg.get(key):
            raise SystemExit(f"{config}: missing '{key}'")
    if len(sha) < 7:
        raise SystemExit("--sha must be a commit SHA")
    slug = kernel_slug(cfg["name"])
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(
        RUN_PY.format(
            run_id=run_id, sha=sha, config_name=cfg["name"], config_yaml=raw_text, repo=REPO
        )
    )
    meta = {
        "id": f"{username}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": bool(cfg.get("gpu", False)),
        "enable_internet": True,
        "dataset_sources": [f"{username}/{cfg['dataset']}"],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("config", type=Path)
    ap.add_argument("--username", required=True)
    ap.add_argument("--sha", required=True)
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    path = build(a.config, a.username, a.sha, a.run_id, a.out)
    meta = json.loads((path / "kernel-metadata.json").read_text())
    print(meta["id"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
