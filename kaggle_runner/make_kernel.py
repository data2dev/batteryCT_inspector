"""Build a Kaggle kernel folder that runs one experiment from a pinned build.

Usage (from the GitHub workflow):
    python -m build --wheel -o dist/
    python kaggle_runner/make_kernel.py CONFIG --username U --sha SHA --run-id ID \\
        --wheel dist/batteryct_inspector-*.whl --out DIR
    kaggle kernels push -p DIR

The batteryct wheel built from commit SHA is embedded (base64) in the generated
``run.py``, so the Kaggle run needs no internet access: it installs the embedded
wheel offline (numpy, Pillow and PyYAML are preinstalled on Kaggle), finds the
attached private dataset under /kaggle/input, runs ``batteryct experiment`` and
writes everything to /kaggle/working/<run_id>/ (collected later by collect.py).
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path

import yaml

MAX_WHEEL_BYTES = 2_000_000  # the batteryct wheel is ~20 kB; guard against mistakes

RUN_PY = '''"""Auto-generated by kaggle_runner/make_kernel.py. Do not edit on Kaggle."""
import base64, hashlib, json, os, platform, subprocess, sys, tempfile, time

RUN_ID = {run_id!r}
SHA = {sha!r}
CONFIG_NAME = {config_name!r}
CONFIG_YAML = {config_yaml!r}
WHEEL_NAME = {wheel_name!r}
WHEEL_SHA256 = {wheel_sha256!r}
WHEEL_B64 = {wheel_b64!r}

out = os.path.join("/kaggle/working", RUN_ID)
os.makedirs(out, exist_ok=True)
t0 = time.time()
meta = {{
    "run_id": RUN_ID,
    "git_sha": SHA,
    "config_name": CONFIG_NAME,
    "wheel": WHEEL_NAME,
    "wheel_sha256": WHEEL_SHA256,
    "status": "started",
}}


def save_meta():
    with open(os.path.join(out, "run_meta.json"), "w") as f:
        json.dump(meta, f, indent=2)


save_meta()
try:
    data = base64.b64decode(WHEEL_B64)
    if hashlib.sha256(data).hexdigest() != WHEEL_SHA256:
        raise RuntimeError("embedded wheel checksum mismatch")
    wheel = os.path.join(tempfile.mkdtemp(), WHEEL_NAME)
    with open(wheel, "wb") as f:
        f.write(data)
    # Offline install of the exact build; dependencies come from Kaggle's image.
    subprocess.check_call(
        [sys.executable, "-m", "pip", "install", "-q", "--no-index", "--no-deps",
         "--force-reinstall", wheel]
    )
    import importlib.metadata as md
    for dist in ("numpy", "pillow", "pyyaml", "torch", "torchvision"):
        try:
            meta.setdefault("deps", {{}})[dist] = md.version(dist)
        except md.PackageNotFoundError:
            pass
    meta["batteryct_version"] = md.version("batteryct-inspector")
    cfg_path = os.path.join(out, "config.yaml")
    with open(cfg_path, "w") as f:
        f.write(CONFIG_YAML)
    subprocess.check_call(
        [sys.executable, "-m", "batteryct.cli", "experiment", cfg_path,
         "--data", "/kaggle/input", "--out", out]
    )
    meta["status"] = "complete"
except Exception as e:  # record the failure in the collected output, then fail the kernel
    meta["status"] = "error"
    meta["error"] = repr(e)
    raise
finally:
    meta["runtime_s"] = round(time.time() - t0, 1)
    meta["python"] = platform.python_version()
    try:
        import torch  # noqa: F401
        meta["gpu"] = torch.cuda.get_device_name(0) if torch.cuda.is_available() else None
    except Exception:
        meta["gpu"] = None
    save_meta()
'''


def kernel_slug(config_name: str) -> str:
    slug = "batteryct-" + "".join(c if c.isalnum() else "-" for c in config_name.lower())
    return "-".join(p for p in slug.split("-") if p)[:50]


def build(config: Path, username: str, sha: str, run_id: str, wheel: Path, out: Path) -> Path:
    raw_text = config.read_text()
    cfg = yaml.safe_load(raw_text) or {}
    for key in ("name", "dataset"):
        if not cfg.get(key):
            raise SystemExit(f"{config}: missing '{key}'")
    if len(sha) < 7:
        raise SystemExit("--sha must be a commit SHA")
    if not wheel.is_file() or not wheel.name.endswith(".whl"):
        raise SystemExit(f"--wheel must be a built .whl file, got {wheel}")
    data = wheel.read_bytes()
    if len(data) > MAX_WHEEL_BYTES:
        raise SystemExit(f"{wheel} is {len(data)} bytes; refusing to embed (> {MAX_WHEEL_BYTES})")
    slug = kernel_slug(cfg["name"])
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(
        RUN_PY.format(
            run_id=run_id,
            sha=sha,
            config_name=cfg["name"],
            config_yaml=raw_text,
            wheel_name=wheel.name,
            wheel_sha256=hashlib.sha256(data).hexdigest(),
            wheel_b64=base64.b64encode(data).decode("ascii"),
        )
    )
    meta = {
        "id": f"{username}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": bool(cfg.get("gpu", False)),
        # Ask for a specific GPU (Kaggle's current default). Kaggle only grants GPUs to
        # phone-verified accounts and otherwise silently runs on CPU; experiment.py
        # refuses to continue on CPU when the config says gpu: true.
        **(
            {"machine_shape": str(cfg.get("accelerator", "NvidiaTeslaT4"))}
            if cfg.get("gpu")
            else {}
        ),
        # Off by default: the code is embedded, data is an attached dataset. Kaggle only
        # allows internet for phone-verified accounts; set `internet: true` in a config
        # if a method must download something (e.g. pretrained weights).
        "enable_internet": bool(cfg.get("internet", False)),
        "dataset_sources": [
            f"{username}/{d}" for d in [cfg["dataset"], *(cfg.get("extra_datasets") or [])]
        ],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("config", type=Path)
    ap.add_argument("--username", required=True)
    ap.add_argument("--sha", required=True)
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--wheel", type=Path, required=True, help="batteryct wheel built from --sha")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    path = build(a.config, a.username, a.sha, a.run_id, a.wheel, a.out)
    meta = json.loads((path / "kernel-metadata.json").read_text())
    print(meta["id"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
